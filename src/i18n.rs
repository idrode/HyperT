//! Internacionalización central del TUI.
//!
//! La interfaz se publica en INGLÉS por defecto (para GitHub); el español es
//! opcional (`--lang=es` o la tecla `L` de toggle). Los textos que ve el
//! usuario viven aquí, no como literales repartidos por `src/ui/` — así una
//! vista nueva se añade a ambos idiomas en un solo sitio.
//!
//! Nota: esto NO cambia el idioma de desarrollo (CLAUDE.md, instrucciones a
//! Claude Code) — solo los textos de la interfaz.

use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Es,
}

// 0 = En (por defecto), 1 = Es. Global porque los `draw` de las vistas no
// llevan el idioma como parámetro y no tiene sentido enhebrarlo por todos.
static LANG: AtomicU8 = AtomicU8::new(0);

pub fn set_lang(l: Lang) {
    LANG.store(l as u8, Ordering::Relaxed);
}

pub fn lang() -> Lang {
    if LANG.load(Ordering::Relaxed) == 1 {
        Lang::Es
    } else {
        Lang::En
    }
}

/// Alterna En ↔ Es (tecla `L`).
pub fn toggle_lang() {
    let next = if lang() == Lang::En { Lang::Es } else { Lang::En };
    set_lang(next);
}

/// `--lang=en` / `--lang=es` (o `en`/`es` sueltos). None si no reconoce.
pub fn parse_lang(s: &str) -> Option<Lang> {
    match s.trim().to_ascii_lowercase().as_str() {
        "en" | "english" | "ingles" | "inglés" => Some(Lang::En),
        "es" | "spanish" | "espanol" | "español" => Some(Lang::Es),
        _ => None,
    }
}

/// Textos activos según el idioma actual. Uso: `i18n::t().foo`.
pub fn t() -> &'static Strings {
    match lang() {
        Lang::En => &EN,
        Lang::Es => &ES,
    }
}

/// Filas de la ayuda (`?`) del idioma actual.
pub fn help_rows() -> &'static [HelpRow] {
    match lang() {
        Lang::En => HELP_EN,
        Lang::Es => HELP_ES,
    }
}

