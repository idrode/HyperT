#[cfg(test)]
mod tests {
    use super::*;

    // Un solo test muta el estado global LANG (los tests corren en paralelo y
    // lo comparten): default En, toggle y selección por idioma juntos aquí.
    #[test]
    fn estado_global_de_idioma() {
        set_lang(Lang::En);
        assert_eq!(lang(), Lang::En);
        assert_eq!(t().tab_pair, "Pair");
        toggle_lang();
        assert_eq!(lang(), Lang::Es);
        assert_eq!(t().tab_pair, "Par");
        toggle_lang();
        assert_eq!(lang(), Lang::En);
    }

    #[test]
    fn parse_lang_reconoce_valores() {
        // solo el valor, no el flag entero
        assert!(parse_lang("--lang=es").is_none());
        assert_eq!(parse_lang("ES"), Some(Lang::Es));
        assert_eq!(parse_lang("en"), Some(Lang::En));
        assert_eq!(parse_lang("fr"), None);
    }

    #[test]
    fn ambos_idiomas_tienen_igual_numero_de_filas_de_ayuda() {
        assert_eq!(HELP_EN.len(), HELP_ES.len());
    }
}
